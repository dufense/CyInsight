/**
 * Simplified world country polygons pre-projected to 960×500 Mercator space.
 * Projection: x = (lon + 180) * 2.6667, y = (90 - lat) * 2.7778
 * These are intentionally simplified for fast SVG rendering.
 */
export interface CountryShape {
  code: string;
  paths: number[][][]; // Array of polygons, each polygon is array of [x,y] points
}

function project(lon: number, lat: number): [number, number] {
  return [(lon + 180) * 2.6667, (90 - lat) * 2.7778];
}

function poly(...pts: [number, number][]): number[][] {
  return pts.map(([lon, lat]) => project(lon, lat));
}

