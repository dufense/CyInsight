/**
 * Convert country shape paths to SVG path string
 */
export function shapeToPath(shape: CountryShape, scaleX: number, scaleY: number): string {
  return shape.paths.map(polygon => {
    if (!polygon[0] || polygon[0].length < 2) return "";
    const pts = polygon[0];
    const d = pts.map((p, i) => {
      const x = (p[0] * scaleX).toFixed(1);
      const y = (p[1] * scaleY).toFixed(1);
      return `${i === 0 ? "M" : "L"} ${x} ${y}`;
    }).join(" ");
    return d + " Z";
  }).join(" ");
}
